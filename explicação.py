#if, elif e else são usados para criar estruturas de decisão em Python. Eles permitem que você execute diferentes blocos de código com base em condições específicas.

#Python usa indentação para definir blocos de código. torna seu código muito mais limpo e fácil de ler!

#Declaração If-Else
temperature = 28

if temperature > 30:
    print("It's hot outside!")
elif temperature > 20:
    print("It's a nice day.")
else:
    print("It's a bit chilly.")


